// Generates supabase/seed.sql from the verified PoC data in src/data/*.json (run: npm run seed)
import fs from 'node:fs';
const j = (f) => JSON.parse(fs.readFileSync(`src/data/${f}.json`, 'utf8'));
const q = (s) => `'${String(s).replace(/'/g, "''")}'`;
const arr = (a) => `array[${a.map(q).join(',')}]::text[]`;
const out = [];
for (const [k, p] of Object.entries(j('products')))
  out.push(`insert into public.products (key,name,price_pence,pack_size,unit,slug) values (${q(k)},${q(p.n)},${p.pr},${p.pack},${q(p.u)},${q(p.s)});`);
for (const [k, v] of Object.entries(j('cupboard')))
  out.push(`insert into public.cupboard_items (key,info) values (${q(k)},${q(v)});`);
for (const r of j('recipes')) {
  out.push(`insert into public.recipes (id,course,emoji,name,protein_g,kcal,serves,method,cupboard) values (${q(r.id)},${q(r.c)},${q(r.e)},${q(r.n)},${r.p},${r.k},${r.serves},${arr(r.m)},${arr(r.cup)});`);
  for (const [pk, qty] of r.fresh)
    out.push(`insert into public.recipe_ingredients (recipe_id,product_key,qty) values (${q(r.id)},${q(pk)},${qty});`);
}
fs.writeFileSync('supabase/seed.sql', '-- generated by scripts/gen-seed.mjs; do not edit\n' + out.join('\n') + '\n');
console.log(out.length, 'statements');
