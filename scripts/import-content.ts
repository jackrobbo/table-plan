// npm run content:import — validates content/, then compiles app data + supabase/seed.sql.
import fs from 'node:fs';
import path from 'node:path';
import crypto from 'node:crypto';
import type { IngredientDef, RecipeDef } from '../src/lib/content/types';
import { deriveAllergens, validateContent } from '../src/lib/content/validate';

const readJson = <T>(f: string) => JSON.parse(fs.readFileSync(f, 'utf8')) as T;
const ingredients = readJson<IngredientDef[]>('content/ingredients.json');
const recipes: RecipeDef[] = [];
for (const f of fs.readdirSync('content/recipes').filter((f) => f.endsWith('.json')).sort()) {
  const v = readJson<RecipeDef | RecipeDef[]>(path.join('content/recipes', f));
  recipes.push(...(Array.isArray(v) ? v : [v])); // a file may hold one recipe or a batch
}

const issues = validateContent(ingredients, recipes);
for (const i of issues) console.log(`${i.level === 'error' ? '✖' : '⚠'} ${i.where}: ${i.message}`);
const errors = issues.filter((i) => i.level === 'error').length;
console.log(`${recipes.length} recipes, ${ingredients.length} ingredients — ${errors} errors, ${issues.length - errors} warnings`);
if (errors) { console.error('Fix errors before importing; nothing written.'); process.exit(1); }

const ingMap = new Map(ingredients.map((i) => [i.slug, i]));
const byStatus = (s: string) => recipes.filter((r) => r.status === s).length;
console.log(`live ${byStatus('live')} · verified ${byStatus('verified')} · draft ${byStatus('draft')}`);

// ---- compiled app data (live recipes only; shape consumed by src/data/index.ts) ----
const out = (f: string, v: unknown) => fs.writeFileSync(`src/data/${f}.json`, JSON.stringify(v, null, 1) + '\n');
out('products', Object.fromEntries(ingredients.filter((i) => i.product).map((i) => [i.slug,
  { n: i.product!.name, pr: i.product!.price_pence, pack: i.product!.pack_size, u: i.unit, s: i.product!.slug }])));
out('cupboard', Object.fromEntries(ingredients.filter((i) => i.cupboard).map((i) => [i.slug, i.note ?? i.name])));
out('recipes', recipes.filter((r) => r.status === 'live').map((r) => ({
  id: r.slug, c: r.course, e: r.emoji ?? '🍽️', n: r.name, p: r.per_portion.protein_g, k: r.per_portion.kcal, serves: r.serves,
  macros_only: r.macros_only ?? false,
  fresh: r.ingredients.map((l) => [l.ingredient, l.qty]), cup: r.cupboard, m: r.method,
  allergens: deriveAllergens(r, ingMap),
})));

// ---- idempotent SQL ----
const q = (s: unknown) => (s == null ? 'null' : `'${String(s).replace(/'/g, "''")}'`);
const n = (v: unknown) => (v == null ? 'null' : String(v));
const arr = (a: string[]) => `array[${a.map(q).join(',')}]::text[]`;
const sql: string[] = ['-- generated by scripts/import-content.ts; do not edit', 'begin;'];
for (const i of ingredients) {
  const p = i.per100;
  sql.push(`insert into public.ingredients (slug,name,unit,cupboard,note,allergens,kcal_100,protein_100,carbs_100,fat_100,cofid_code,cofid_verified) values (${q(i.slug)},${q(i.name)},${q(i.unit)},${i.cupboard},${q(i.note)},${arr(i.allergens)},${n(p?.kcal)},${n(p?.protein_g)},${n(p?.carbs_g)},${n(p?.fat_g)},${q(i.cofid?.code)},${!!i.cofid?.verified}) on conflict (slug) do update set name=excluded.name,unit=excluded.unit,cupboard=excluded.cupboard,note=excluded.note,allergens=excluded.allergens,kcal_100=excluded.kcal_100,protein_100=excluded.protein_100,carbs_100=excluded.carbs_100,fat_100=excluded.fat_100,cofid_code=excluded.cofid_code,cofid_verified=excluded.cofid_verified;`);
  if (i.product) sql.push(`insert into public.products (ingredient_slug,retailer,name,price_pence,pack_size,slug) values (${q(i.slug)},${q(i.product.retailer)},${q(i.product.name)},${i.product.price_pence},${i.product.pack_size},${q(i.product.slug)}) on conflict (ingredient_slug,retailer) do update set name=excluded.name,price_pence=excluded.price_pence,pack_size=excluded.pack_size,slug=excluded.slug,updated_at=now();`);
}
for (const r of recipes) {
  const hash = crypto.createHash('sha256').update(JSON.stringify(r)).digest('hex').slice(0, 16);
  const m = r.per_portion;
  sql.push(`insert into public.recipes (slug,name,course,emoji,serves,kcal,protein_g,carbs_g,fat_g,method,allergens,status,source,macros_only,content_hash) values (${q(r.slug)},${q(r.name)},${q(r.course)},${q(r.emoji)},${r.serves},${m.kcal},${m.protein_g},${n(m.carbs_g)},${n(m.fat_g)},${arr(r.method)},${arr(deriveAllergens(r, ingMap))},${q(r.status)},${q(r.source)},${!!r.macros_only},${q(hash)}) on conflict (slug) do update set name=excluded.name,course=excluded.course,emoji=excluded.emoji,serves=excluded.serves,kcal=excluded.kcal,protein_g=excluded.protein_g,carbs_g=excluded.carbs_g,fat_g=excluded.fat_g,method=excluded.method,allergens=excluded.allergens,status=excluded.status,source=excluded.source,macros_only=excluded.macros_only,content_hash=excluded.content_hash where public.recipes.content_hash is distinct from excluded.content_hash;`);
  sql.push(`delete from public.recipe_ingredients where recipe_slug=${q(r.slug)};`);
  for (const l of r.ingredients) sql.push(`insert into public.recipe_ingredients (recipe_slug,ingredient_slug,qty,cupboard) values (${q(r.slug)},${q(l.ingredient)},${l.qty},false);`);
  for (const c of r.cupboard) sql.push(`insert into public.recipe_ingredients (recipe_slug,ingredient_slug,qty,cupboard) values (${q(r.slug)},${q(c)},0,true);`);
}
sql.push('commit;');
fs.writeFileSync('supabase/seed.sql', sql.join('\n') + '\n');
console.log('wrote src/data/*.json and supabase/seed.sql');
